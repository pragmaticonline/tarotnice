// Minimal HTML escaping for server-rendered pages. Everything
// user-supplied (questions, nicknames, journal notes) goes through
// this before it reaches the page.
export function escapeHtml(value: string | null | undefined): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
